#!/usr/bin/env bash
# Usage: 13-cross-link-toolchain.sh <triple> [program...]
#
# Relinks the toolchain's programs for another platform (today: x86_64-pc-windows-gnu and
# aarch64-pc-windows-gnu) with the host's dist/scalino-linkdriver, from the NIR the host build
# (03, 04, 04d, 07, 08) left in .build-work/, so nothing is compiled again except the CLI's
# one platform file (cli/selfexe/*.scala). The result is dist-cross/<triple>/, the host dist/
# with its platform binaries swapped for the target's: <triple> is what release.yml zips.
#
#   programs: dotc linkdriver jslink cli lsp   (default: all of them)
#
# Needs the host build's output, and `scalino sysroot build <triple>` (run here if missing).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
source ./00-env.sh
source ./link-lib.sh
source ./buildinfo-lib.sh

TRIPLE="${1:?usage: $0 <triple> [program...]}"; shift
PROGRAMS=("$@"); [[ ${#PROGRAMS[@]} -gt 0 ]] || PROGRAMS=(dotc linkdriver jslink cli lsp)
case "$TRIPLE" in
  *-pc-windows-gnu) EXE=".exe"; SELFEXE="$ROOT/cli/selfexe/Windows.scala" ;;
  *) echo "13-cross-link-toolchain.sh: unsupported target $TRIPLE" >&2; exit 1 ;;
esac

OUT="$ROOT/dist-cross/$TRIPLE"
CROSS_WORK="$WORK/cross/$TRIPLE"
mkdir -p "$CROSS_WORK"

SCALINO="$DIST/scalino"
[[ -x "$SCALINO" && -x "$DIST/scalino-linkdriver" ]] || { echo "run the host build (build/all.sh) first" >&2; exit 1; }
"$SCALINO" sysroot build "$TRIPLE" >&2
SYSROOT="$("$SCALINO" sysroot path "$TRIPLE")"
LLD="$(command -v ld.lld || "$SCALINO" sysroot lld | tail -1)"

# The compiler recurses deeply: Windows' 1 MB default main-thread stack overflows where Linux's 8 MB and
# macOS's 8 MB do not, so every program gets 64 MB (reserved, not committed): `-Wl,--stack,N` above.
# cross_link <name> <classpath> <main class> [LinkDriver flags...]: links into $CROSS_WORK/<name>
# and copies the binary to $CROSS_WORK/<name>.bin
cross_link() {
  local name="$1" cp="$2" main="$3"; shift 3
  local dir="$CROSS_WORK/$name"
  rm -rf "$dir"; mkdir -p "$dir"
  # Windows has no direct LLVM-C codegen yet (textual IR through clang), which is also what
  # the linkdriver defaults to for a Windows target.
  LINK_ENV=()
  linkdriver_run "$cp" "$(to_native_path "$dir")" "$main" \
    --target-triple "$TRIPLE" --sysroot "$TRIPLE=$SYSROOT" --ld-path "$LLD" \
    --lto none --linking -Wl,--stack,67108864 ${SCALINO_WINDOWS_PDB:+--linking -Wl,--pdb=} "$@"
  local built="$dir/$TRIPLE/$main$EXE"
  [[ -f "$built" ]] || built="$(find "$dir" -type f -name "$main$EXE" | head -1)"
  # SCALINO_WINDOWS_PDB=1: a PDB of public symbols next to the program, so Windows' stack traces name
  # the Scala methods instead of the nearest exported C function (copy it next to the .exe)
  [[ -z "${SCALINO_WINDOWS_PDB:-}" ]] || find "$dir" -name '*.pdb' -exec cp {} "$CROSS_WORK/$name.pdb" \;
  [[ -f "$built" ]] || { echo "link of $name did not produce $main$EXE under $dir" >&2; exit 1; }
  cp "$built" "$CROSS_WORK/$name.bin"
}

wants() { local p; for p in "${PROGRAMS[@]}"; do [[ "$p" == "$1" ]] && return 0; done; return 1; }
MODE="$SCALINO_LINK_MODE"

if wants dotc; then
  echo "== cross-linking scalino-dotc for $TRIPLE =="
  cross_link dotc "$(to_native_path "$WORK/selfhost/nir-out")$CP_SEP$(cat "$WORK/selfhost/nativelibs.cp")" \
    dotty.tools.dotc.Main --mode "$MODE" --multithreading --no-incremental-compilation --embed-resources
fi

if wants linkdriver; then
  echo "== cross-linking scalino-linkdriver for $TRIPLE =="
  # The linkdriver embeds the direct LLVM-C codegen's bindings, which a link needs libLLVM for
  # (04-build-scalino-linkdriver.sh). A Windows linkdriver has no direct codegen (it goes through
  # clang, see LinkDriver.windowsTarget), so its LLVM-C functions are stubs that abort.
  STUB_DIR="$CROSS_WORK/llvm-stub"
  rm -rf "$STUB_DIR"; mkdir -p "$STUB_DIR/scala-native"
  {
    echo '// generated by build/13-cross-link-toolchain.sh: LLVM-C is not linked on this target, direct codegen is off.'
    echo '#include <stdlib.h>'
    grep -ho 'def LLVM[A-Za-z0-9_]*' "$ROOT"/patches/scala-native-0006-codegen.patch | sed 's/^def //' | sort -u \
      | while read -r f; do echo "void *$f(void) { abort(); }"; done
  } > "$STUB_DIR/scala-native/llvm_stub.c"
  # Compiled again, with the native dotc, so the Windows build has the current LinkDriver.scala.
  DRIVER_CLASSES="$CROSS_WORK/driver-classes"
  rm -rf "$DRIVER_CLASSES"; mkdir -p "$DRIVER_CLASSES"
  "$DIST/scalino-dotc" -javabootclasspath "$DIST/java.base.jar" \
    -Xplugin:"$(cat "$WORK/nscplugin.jar.txt")" -Xplugin-require:scalanative \
    -classpath "$(cat "$WORK/tools-patched-javalib.cp")" -d "$DRIVER_CLASSES" "$ROOT/src/LinkDriver.scala"
  cross_link linkdriver "$(to_native_path "$DRIVER_CLASSES")$CP_SEP$(to_native_path "$STUB_DIR")$CP_SEP$(cat "$WORK/tools-patched-javalib.cp")" \
    LinkDriver --mode "$MODE" --multithreading --no-incremental-compilation
fi

if wants jslink; then
  echo "== cross-linking scalino-jslink for $TRIPLE =="
  cross_link jslink "$(to_native_path "$WORK/jslink-classes")$CP_SEP$(to_native_path "$WORK/jslink-resources")$CP_SEP$(cat "$WORK/jslink-nativelibs.cp")" \
    JsLink --mode "$([[ "$MODE" == debug ]] && echo debug || echo release-size)" --multithreading --embed-resources --no-incremental-compilation
fi

if wants lsp; then
  echo "== cross-linking scalino-lsp for $TRIPLE =="
  # jsoniter-scala-core's C code calls MSVC's __mulh/__umulh. Same file as LinkDriver.writeWindowsCompat, which a
  # linkdriver built from the current source adds itself; the host's may predate it.
  COMPAT_DIR="$CROSS_WORK/windows-compat"
  mkdir -p "$COMPAT_DIR/scala-native"
  cat > "$COMPAT_DIR/scala-native/scalino_windows_compat.c" <<'EOF'
#if defined(_WIN64)
__attribute__((weak)) long long __mulh(long long x, long long y) { return (long long)(((__int128)x * y) >> 64); }
__attribute__((weak)) unsigned long long __umulh(unsigned long long x, unsigned long long y) {
  return (unsigned long long)(((unsigned __int128)x * y) >> 64);
}
#endif
EOF
  cross_link lsp "$(cat "$WORK/selfhost/lsp-link.cp")$CP_SEP$(to_native_path "$COMPAT_DIR")" dotty.tools.languageserver.Main \
    --mode "$MODE" --multithreading --no-incremental-compilation
fi

if wants cli; then
  echo "== cross-linking scalino for $TRIPLE =="
  # Same compile as 07-build-scalino.sh, with the target's SelfExe in place of the host's.
  CLASSES_DIR="$CROSS_WORK/cli-classes"
  rm -rf "$CLASSES_DIR"; mkdir -p "$CLASSES_DIR"
  NIR_NATIVE_CP=""
  for artifact in "org.scala-native:nir_native0.5_3:$SCALA_NATIVE_VERSION" "org.scala-native:util_native0.5_3:$SCALA_NATIVE_VERSION"; do
    jar="$(cs fetch -r ivy2Local --intransitive "$artifact" --classpath | tr -d '\r')"
    NIR_NATIVE_CP="${NIR_NATIVE_CP:+$NIR_NATIVE_CP$CP_SEP}$jar"
  done
  NATIVELIBS_CP="$WORK/scalino-src/nativelibs.cp"
  # regenerated: the host build's may predate a pin
  write_buildinfo "$CROSS_WORK/BuildInfo.scala"
  "$DIST/scalino-dotc" \
    -javabootclasspath "$DIST/java.base.jar" \
    -classpath "$(cat "$WORK/compiler.cp")$CP_SEP$(cat "$NATIVELIBS_CP")$CP_SEP$NIR_NATIVE_CP" \
    -Xplugin:"$(cat "$WORK/nscplugin.jar.txt")" -Xplugin-require:scalanative \
    -Yretain-trees -d "$CLASSES_DIR" \
    "$ROOT/cli/ScalinoCli.scala" "$ROOT/cli/Packaging.scala" "$ROOT/cli/Sysroot.scala" "$ROOT/cli/SysrootBuild.scala" \
    "$CROSS_WORK/BuildInfo.scala" "$SELFEXE"
  cross_link cli "$(to_native_path "$CLASSES_DIR")$CP_SEP$(cat "$NATIVELIBS_CP")$CP_SEP$NIR_NATIVE_CP" ScalinoCli \
    --mode "$([[ "$MODE" == debug ]] && echo debug || echo release-size)" --multithreading --no-incremental-compilation
fi

# SCALINO_CROSS_PROGRAMS_ONLY=1: stop at the .bin files in $CROSS_WORK (ci.yml's lsp job)
[[ -z "${SCALINO_CROSS_PROGRAMS_ONLY:-}" ]] || { echo "OK: programs in $CROSS_WORK"; exit 0; }

# Assemble dist-cross/<triple>/: everything platform-independent from dist/, the target's binaries.
mkdir -p "$OUT"
rsync -a --exclude 'scalino' --exclude 'scalino-dotc' --exclude 'scalino-linkdriver' --exclude 'scalino-jslink' \
  --exclude 'scalino-lsp' --exclude 'scalino-cs' "$DIST/" "$OUT/"
install_bin() { [[ -f "$CROSS_WORK/$1.bin" ]] && cp "$CROSS_WORK/$1.bin" "$OUT/$2$EXE" || true; }
install_bin cli scalino
# The class path manifests (dist-relative lib/*.jar entries) use the host's separator; Windows' is ';'
for f in compiler.cp nativelibs.cp jslibs.cp; do
  [[ -f "$OUT/$f" ]] && tr ':' ';' < "$DIST/$f" | tr -d '\n' > "$OUT/$f"
done
# coursier: the host's `cs` is for the host, so the target's comes from coursier's releases
CS_ZIP="$CROSS_WORK/cs-x86_64-pc-win32-$COURSIER_WINDOWS_VERSION.zip"
if [[ ! -f "$CS_ZIP" ]]; then
  curl -fsSL -o "$CS_ZIP.part" "https://github.com/coursier/coursier/releases/download/v$COURSIER_WINDOWS_VERSION/cs-x86_64-pc-win32.zip"
  mv "$CS_ZIP.part" "$CS_ZIP"
fi
echo "$COURSIER_WINDOWS_X86_64_SHA256  $CS_ZIP" | shasum -a 256 -c - >&2
unzip -p "$CS_ZIP" cs-x86_64-pc-win32.exe > "$OUT/scalino-cs.exe"
install_bin dotc scalino-dotc
install_bin linkdriver scalino-linkdriver
install_bin jslink scalino-jslink
install_bin lsp scalino-lsp
echo "OK: $OUT"
